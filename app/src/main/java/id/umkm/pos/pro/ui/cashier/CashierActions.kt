package id.umkm.pos.pro.ui.cashier

import id.umkm.pos.pro.core.model.PaymentMethod
import id.umkm.pos.pro.ui.shift.NoOpShiftLauncher
import id.umkm.pos.pro.ui.shift.ShiftLauncher

class CashierActions(
    val onSearchQueryChange: (String) -> Unit,
    val onCatalogCategoryChange: (String?) -> Unit,
    val onCatalogAvailableOnlyChange: (Boolean) -> Unit,
    val onRetryCatalog: () -> Unit,
    val onAddProduct: (Long) -> Unit,
    val onDecreaseProductQuantity: (Long) -> Unit,
    val onIncreaseQuantity: (String) -> Unit,
    val onDecreaseQuantity: (String) -> Unit,
    val onRemoveLine: (String) -> Unit,
    val onOpenCartSheet: () -> Unit,
    val onCloseCartSheet: () -> Unit,
    val onOpenLineEditor: (String) -> Unit,
    val onCloseLineEditor: () -> Unit,
    val onLineEditorUnitChange: (Long?) -> Unit,
    val onLineEditorPriceChange: (String) -> Unit,
    val onLineEditorDiscountChange: (String) -> Unit,
    val onApplyLineEditor: () -> Unit,
    val onOpenPaymentSheet: () -> Unit,
    val onClosePaymentSheet: () -> Unit,
    val onPaymentMethodChange: (PaymentMethod) -> Unit,
    val onAmountReceivedChange: (String) -> Unit,
    val onConfirmCharge: () -> Unit,
    val onPrintReceipt: () -> Unit,
    val onNewSale: () -> Unit,
    val onMessageConsumed: () -> Unit,
    val onOpenScanDialog: () -> Unit = {},
    val onDismissScanDialog: () -> Unit = {},
    val onScannedCode: (String) -> Unit = {},
    val onClearCart: () -> Unit = {},
    val onOpenShift: (cartItemCount: Int, onClearCart: () -> Unit) -> Unit = { _, _ -> },
    val onOpenQuickShift: (onOpened: () -> Unit) -> Unit = {},
    val onShiftOpenedForPayment: () -> Unit = {},
    val onShiftPromptConsumed: () -> Unit = {},
) {
    companion object {
        fun from(
            viewModel: CashierViewModel,
            shiftLauncher: ShiftLauncher = NoOpShiftLauncher,
        ): CashierActions = CashierActions(
            onSearchQueryChange = viewModel::onSearchQueryChange,
            onCatalogCategoryChange = viewModel::onCatalogCategoryChange,
            onCatalogAvailableOnlyChange = viewModel::onCatalogAvailableOnlyChange,
            onRetryCatalog = viewModel::onRetryCatalog,
            onAddProduct = viewModel::onAddProduct,
            onDecreaseProductQuantity = viewModel::onDecreaseProductQuantity,
            onIncreaseQuantity = viewModel::onIncreaseQuantity,
            onDecreaseQuantity = viewModel::onDecreaseQuantity,
            onRemoveLine = viewModel::onRemoveLine,
            onOpenCartSheet = viewModel::onOpenCartSheet,
            onCloseCartSheet = viewModel::onCloseCartSheet,
            onOpenLineEditor = viewModel::onOpenLineEditor,
            onCloseLineEditor = viewModel::onCloseLineEditor,
            onLineEditorUnitChange = viewModel::onLineEditorUnitChange,
            onLineEditorPriceChange = viewModel::onLineEditorPriceChange,
            onLineEditorDiscountChange = viewModel::onLineEditorDiscountChange,
            onApplyLineEditor = viewModel::onApplyLineEditor,
            onOpenPaymentSheet = viewModel::onOpenPaymentSheet,
            onClosePaymentSheet = viewModel::onClosePaymentSheet,
            onPaymentMethodChange = viewModel::onPaymentMethodChange,
            onAmountReceivedChange = viewModel::onAmountReceivedChange,
            onConfirmCharge = viewModel::onConfirmCharge,
            onPrintReceipt = viewModel::onPrintReceipt,
            onNewSale = viewModel::onNewSale,
            onMessageConsumed = viewModel::onMessageConsumed,
            onOpenScanDialog = viewModel::onOpenScanDialog,
            onDismissScanDialog = viewModel::onDismissScanDialog,
            onScannedCode = viewModel::onScannedCode,
            onClearCart = viewModel::onClearCart,
            onOpenShift = shiftLauncher::openShift,
            onOpenQuickShift = shiftLauncher::openQuickShift,
            onShiftOpenedForPayment = viewModel::onShiftOpenedForPayment,
            onShiftPromptConsumed = viewModel::onShiftPromptConsumed,
        )
    }
}
